def detect_phone(number: str) -> dict:
    """识别手机号的运营商和归属地。

    参数：
        number: 原始手机号字符串（可含空格、横线等非数字字符）

    返回字典字段说明：
        - carrier: 运营商名称，如 "中国移动"，未知则返回 "未知运营商"
        - region: 归属地，如 "北京"，未知则返回 "未知"
        - valid: 是否为有效手机号（11位且以1开头）

    处理逻辑：
        1. 去除所有非数字字符
        2. 校验长度=11 且首位=1
        3. 取前3位号段查 SEGMENT_MAP
    """
    number = re.sub(r"\D", "", number or "")   # 去除所有非数字字符
    if len(number) != 11 or not number.startswith("1"):
        return {"carrier": "未知", "region": "未知", "valid": False}
    prefix = number[:3]   # 取前3位号段
    info = SEGMENT_MAP.get(prefix)
    if info:
        return {"carrier": info[0], "region": info[1], "valid": True}
    return {"carrier": "未知运营商", "region": "未知", "valid": True}


def mask_number(number: str) -> str:
    """手机号脱敏：138****8888（中间4位用 * 替代）。

    参数：
        number: 原始11位手机号

    脱敏规则：
        - 取前3位 + "****" + 后4位
        - 长度不足11位则返回原值

    用途：对外展示时隐藏中间4位，保护用户隐私
    """
    if not number or len(number) != 11:
        return number
    return f"{number[:3]}****{number[7:]}"
